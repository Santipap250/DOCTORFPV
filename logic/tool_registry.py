def get_tools(category=None, status=None):
    """Return registry entries, optionally filtered by category/status."""
    tools = TOOL_REGISTRY
    if category:
        tools = [t for t in tools if t['category'] == category.upper()]
    if status:
        tools = [t for t in tools if t['status'] == status]
    return tools


def get_tool_by_route(route):
    """Look up a single registry entry by its route, or None."""
    for t in TOOL_REGISTRY:
        if t['route'] == route:
            return t
    return None


def get_categories():
    """Ordered list of distinct categories present in the registry."""
    seen = []
    for t in TOOL_REGISTRY:
        if t['category'] not in seen:
            seen.append(t['category'])
    return seen
