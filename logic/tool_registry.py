# logic/tool_registry.py
# ============================================================
# OBIX ConfigDoctor — canonical Tool Registry (Phase 3)
#
# Single source of truth for every public tool/page in the app.
# Generated once from the previously-hand-maintained tool list
# that lived only inside templates/partials/nav.html's Tool
# Launcher JS (TP_TOOLS). That copy has now been removed —
# nav.html reads this registry via a small Jinja-rendered JSON
# blob instead (see partials/nav.html), so there is exactly ONE
# place this data is maintained.
#
# `category` intentionally matches nav.html's existing taxonomy
# (TUNE / HW / ANALYZE / VIDEO / EXPLORE) rather than the newer
# landing-page grouping (TUNE/HARDWARE/SETUP/LEARN) used for the
# Command Center — nav.html's desktop mega-menu has several
# dropdown blocks keyed on these exact category strings, and
# renaming them is out of scope for this batch. The Command
# Center (Phase 2) maps these onto its own display groups instead
# of renaming the registry itself.
#
# Consumers:
#   - templates/partials/nav.html  (Tool Launcher search/panel)
#   - blueprints/meta.py           (sitemap.xml generation)
#   - landing.html command center  (Phase 2 — future batch)
#
# Each entry:
#   id                    stable slug, e.g. "app", "pid-advisor"
#   route                 the Flask URL path
#   label                 display name
#   description           short Thai description (shown in UI)
#   category              TUNE | HW | ANALYZE | VIDEO | EXPLORE
#   icon                  inline Lucide SVG markup
#   priority              sitemap priority (0.0-1.0)
#   changefreq            sitemap changefreq
#   status                stable | beta | experimental
#   input_type            what the user provides
#   output_type           what the tool produces
#   firmware_dependency   True if output includes Betaflight CLI
#                         syntax that can vary by firmware version
#   keywords              search terms for the Tool Launcher
# ============================================================

